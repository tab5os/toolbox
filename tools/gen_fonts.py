#!/usr/bin/env python3
"""Generate fonts/tb_sym_*.c: the few symbols Toolbox needs that the OS fonts lack
(Omega for ohms, the minus sign, approximately, less/greater or
equal), from the same pinned Roboto and lv_font_conv settings as the OS.

    python3 tools/gen_fonts.py        # needs Node (npx) and network once

Each font holds only these glyphs. At run time the app sets an OS font as
its fallback (ui_font() in ui.c), so a label using it draws everything
else with the OS font, at the OS font's line height.
"""
import hashlib
import os
import re
import subprocess
import sys
import urllib.request

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(HERE, "build", "fontcache")
LV_FONT_CONV = "lv_font_conv@1.5.3"
ROBOTO = ("https://raw.githubusercontent.com/googlefonts/roboto/"
          "38062f4b4a0be4346d07a928408da21602545e9e/src/hinted/Roboto-Regular.ttf",
          "56a45233d29f11b4dfb86d248e921939d115778f87325e7ae8cc108383d6664d")
# Omega, minus, approximately, less-or-equal, greater-or-equal.
RANGES = "0x3A9,0x2212,0x2248,0x2264,0x2265"
# px sizes of the OS's Roboto Regular roles: caption, body2, body1/subtitle1, headline5, headline4.
SIZES = (24, 28, 32, 48, 68)


def fetch():
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, "Roboto-Regular.ttf")
    url, want = ROBOTO
    if not os.path.exists(path) or hashlib.sha256(open(path, "rb").read()).hexdigest() != want:
        print("download", url)
        data = urllib.request.urlopen(url).read()
        got = hashlib.sha256(data).hexdigest()
        if got != want:
            sys.exit("sha256 mismatch: got %s want %s" % (got, want))
        with open(path, "wb") as f:
            f.write(data)


def conv(size):
    name = "tb_sym_%d" % size
    tmp = os.path.join(CACHE, name + ".c")
    subprocess.run(["npx", "-y", LV_FONT_CONV, "--font", "Roboto-Regular.ttf", "-r", RANGES,
                    "--size", str(size), "--bpp", "4", "--no-compress", "--no-prefilter",
                    "--format", "lvgl", "--lv-font-name", name, "-o", tmp],
                   cwd=CACHE, check=True, stdout=subprocess.DEVNULL)
    text = open(tmp, encoding="utf-8").read()
    text = text.replace('#ifdef LV_LVGL_H_INCLUDE_SIMPLE\n#include "lvgl.h"\n#else\n#include "lvgl/lvgl.h"\n#endif\n',
                        '#include "lvgl.h"\n', 1)
    guard = name.upper()
    text = text.replace("#ifndef %s\n#define %s 1\n#endif\n\n#if %s\n" % (guard, guard, guard), "", 1)
    text = text.replace("#endif /*#if %s*/\n" % guard, "", 1)
    text = re.sub(r" \* Opts: .*\n", " * Opts: --font Roboto-Regular.ttf -r %s --size %d --bpp 4 --no-compress"
                  " --no-prefilter --format lvgl\n" % (RANGES, size), text, count=1)
    # The app fills in fallback and line metrics at run time, so the font
    # can't be const.
    text = re.sub(r"^const lv_font_t %s = \{" % name, "lv_font_t %s = {" % name, text, flags=re.M)
    text = re.sub(r"^lv_font_t %s = \{" % name, "lv_font_t %s = {" % name, text, flags=re.M)
    os.remove(tmp)
    return text


def main():
    fetch()
    os.makedirs(os.path.join(HERE, "fonts"), exist_ok=True)
    for s in SIZES:
        body = conv(s)
        out = os.path.join(HERE, "fonts", "tb_sym_%d.c" % s)
        with open(out, "w", encoding="utf-8") as f:
            f.write("/* Generated by tools/gen_fonts.py from Roboto (Apache License 2.0). Do not edit. */\n" + body)
        print(out)


if __name__ == "__main__":
    main()
